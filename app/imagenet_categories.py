def search_categories(query="", category_filter=None, max_results=1000):
    """Search ImageNet categories by name substring or numeric index.
    Returns list of (index, category_name, formatted_label)."""
    query = str(query).strip().lower()

    # Determine candidate indices based on category_filter
    clean_filter = category_filter.lstrip("★🐶🍕🚗 ").strip() if category_filter else None
    if category_filter == "★ Popular" or clean_filter == "Popular":
        candidates = POPULAR_CLASSES
    elif category_filter in CATEGORY_RANGES:
        candidates = CATEGORY_RANGES[category_filter]
    elif clean_filter in CATEGORY_RANGES:
        candidates = CATEGORY_RANGES[clean_filter]
    else:
        candidates = list(range(len(IMAGENET_CATEGORIES)))

    results = []
    if not query:
        for idx in candidates:
            if idx < len(IMAGENET_CATEGORIES):
                name = IMAGENET_CATEGORIES[idx]
                results.append((idx, name, f"#{idx}: {name}"))
                if len(results) >= max_results:
                    break
        return results

    # If query is digits (or starts with # followed by digits), match exact index or index prefix
    query_num = query.lstrip("# ").strip() if query.startswith("#") else query
    is_digit = query_num.isdigit()
    exact_idx = int(query_num) if is_digit else -1

    # First priority: exact index match
    if 0 <= exact_idx < len(IMAGENET_CATEGORIES) and (
        exact_idx in candidates or category_filter in (None, "All")
    ):
        name = IMAGENET_CATEGORIES[exact_idx]
        results.append((exact_idx, name, f"#{exact_idx}: {name}"))

    # Second priority: name substring match, alias match, or index prefix
    for idx in candidates:
        if idx >= len(IMAGENET_CATEGORIES) or idx == exact_idx:
            continue
        name = IMAGENET_CATEGORIES[idx]
        name_lower = name.lower()
        idx_str = str(idx)
        alias_text = " ".join(_ALIAS_TEXT_BY_INDEX.get(idx, ()))
        if (
            query in name_lower
            or query in alias_text
            or (is_digit and idx_str.startswith(query_num))
        ):
            results.append((idx, name, f"#{idx}: {name}"))
            if len(results) >= max_results:
                break

    return results


def lookup_category(spec):
    """Given an index int/str, category name, or compound '#130: flamingo',
    return (index, name, formatted_label) or None if not found."""
    if spec is None:
        return None
    spec_clean = str(spec).strip().lower()
    if not spec_clean:
        return None

    # Parse compound formats like "#130: flamingo", "130: flamingo", or "130 - flamingo"
    for sep in (":", "—", " - "):
        if sep in spec_clean:
            parts = spec_clean.split(sep, 1)
            candidate_id = parts[0].strip("# ").strip()
            if candidate_id.isdigit():
                idx = int(candidate_id)
                if 0 <= idx < len(IMAGENET_CATEGORIES):
                    name = IMAGENET_CATEGORIES[idx]
                    return idx, name, f"#{idx}: {name}"
                spec_clean = parts[1].strip()
                break

    candidate_num = spec_clean.lstrip("# ").strip()
    if candidate_num.isdigit():
        idx = int(candidate_num)
        if 0 <= idx < len(IMAGENET_CATEGORIES):
            name = IMAGENET_CATEGORIES[idx]
            return idx, name, f"#{idx}: {name}"
        return None

    # Exact match first
    for idx, name in enumerate(IMAGENET_CATEGORIES):
        if name.lower() == spec_clean:
            return idx, name, f"#{idx}: {name}"

    # Common alias (e.g. "monarch butterfly" -> class 323 "monarch")
    alias_idx = CATEGORY_ALIASES.get(spec_clean)
    if alias_idx is not None:
        name = IMAGENET_CATEGORIES[alias_idx]
        return alias_idx, name, f"#{alias_idx}: {name}"

    # Substring match second
    for idx, name in enumerate(IMAGENET_CATEGORIES):
        if spec_clean in name.lower():
            return idx, name, f"#{idx}: {name}"

    # Substring alias match last, so plain name matches still win
    for alias, idx in CATEGORY_ALIASES.items():
        if spec_clean in alias:
            name = IMAGENET_CATEGORIES[idx]
            return idx, name, f"#{idx}: {name}"

    return None
